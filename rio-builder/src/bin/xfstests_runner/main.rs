//! xfstests-port runner for the castore-FUSE (`vm-castore-xfstests`).
//!
//! Every ported xfstests check is a Rust function asserting
//! kernel-visible behavior of a live castore-FUSE mount through direct
//! syscalls — deterministic errnos, no shell, no commands that can
//! prompt or hang. The NixOS testScript only assembles the mount via
//! the production harness (rio-mountd + `spike_mountd_client
//! serve-castore`) and then runs this binary; all filesystem
//! assertions live here.
//!
//! Inputs:
//! * `--mount` — the live FUSE mountpoint, the system under test.
//!   Behavioral assertions ALWAYS target this path.
//! * `--manifest` — the expected-content JSON (see [`manifest`]); the
//!   only oracle. Generated by the VM scenario from the same literals
//!   as the fixture derivation's build script.
//! * `--cache-dir` — rio-mountd's shared backing cache, used to
//!   sequence cold-vs-warm reads and to repair the write-through
//!   probe. Never an assertion target.
//!
//! Output: one `PASS`/`FAIL`/`SKIP` line per check plus `FINDING`
//! lines for documented POSIX divergences, a `SUMMARY` line, and an
//! exit code equal to the number of failures.
//!
//! Selection rationale and the findings register live in
//! `rio-builder/tests/xfstests_port/PLAN.md`. The pure-userspace ports
//! that need no mount are `cargo nextest` tests in
//! `rio-builder/tests/xfstests_port.rs`.
//!
//! NOT production code (same status as `spike_mountd_client`).

mod checks;
mod manifest;

use std::path::PathBuf;
use std::process::ExitCode;

use anyhow::Context;
use clap::Parser;

use crate::checks::{Ctx, Outcome};
use crate::manifest::Manifest;

#[derive(Parser)]
#[command(
    name = "xfstests_runner",
    about = "xfstests ports against a live castore-FUSE mount"
)]
struct Args {
    /// The live castore-FUSE mountpoint (the system under test).
    #[arg(long, required_unless_present = "list")]
    mount: Option<PathBuf>,
    /// Expected-content manifest JSON (the oracle).
    #[arg(long, required_unless_present = "list")]
    manifest: Option<PathBuf>,
    /// rio-mountd's shared backing cache dir. Enables the warm-read
    /// (passthrough) legs and the write-through probe.
    #[arg(long)]
    cache_dir: Option<PathBuf>,
    /// File holding the overlay-leg consumer build's output
    /// (3 lines: dep store path, dir200 count, names count).
    #[arg(long)]
    consumer_output: Option<PathBuf>,
    /// Unprivileged uid for the permission-enforcement probes (the
    /// build uid class).
    #[arg(long, default_value_t = 1000)]
    probe_uid: u32,
    /// Unprivileged gid for the permission-enforcement probes.
    #[arg(long, default_value_t = 990)]
    probe_gid: u32,
    /// Only run checks whose name contains this substring. Note that
    /// the full suite's order is load-bearing for cold-vs-warm read
    /// distinctions; filtered runs are for debugging.
    #[arg(long)]
    filter: Option<String>,
    /// List the registered checks and exit.
    #[arg(long)]
    list: bool,
}

fn main() -> anyhow::Result<ExitCode> {
    let args = Args::parse();
    let registry = checks::registry();

    if args.list {
        for check in &registry {
            println!("{}  [{}]", check.name, check.origin);
        }
        return Ok(ExitCode::SUCCESS);
    }

    let mount = args.mount.context("--mount is required")?;
    let manifest_path = args.manifest.context("--manifest is required")?;
    let manifest = Manifest::load(&manifest_path)?;
    let dep_root = checks::resolve_dep_root(&mount, &manifest)?;

    let ctx = Ctx {
        mount,
        dep_root,
        manifest,
        cache_dir: args.cache_dir,
        consumer_output: args.consumer_output,
        probe_uid: args.probe_uid,
        probe_gid: args.probe_gid,
    };

    let selected: Vec<_> = registry
        .iter()
        .filter(|c| args.filter.as_deref().is_none_or(|f| c.name.contains(f)))
        .collect();
    anyhow::ensure!(
        !selected.is_empty(),
        "no checks match filter {:?}",
        args.filter
    );

    println!(
        "xfstests-runner: mount={} dep={} checks={}",
        ctx.mount.display(),
        ctx.dep_root.display(),
        selected.len()
    );

    let (mut passed, mut failed, mut skipped) = (0u32, 0u32, 0u32);
    for check in &selected {
        println!("RUN  {} [{}]", check.name, check.origin);
        match (check.run)(&ctx) {
            Ok(Outcome::Pass) => {
                passed += 1;
                println!("PASS {}", check.name);
            }
            Ok(Outcome::Skip(reason)) => {
                skipped += 1;
                println!("SKIP {} ({reason})", check.name);
            }
            Err(e) => {
                failed += 1;
                println!("FAIL {} [{}]: {e:#}", check.name, check.origin);
            }
        }
    }
    println!(
        "SUMMARY pass={passed} fail={failed} skip={skipped} total={}",
        selected.len()
    );

    // Exit code = number of failures (clamped to stay inside the
    // meaningful exit-status range).
    Ok(ExitCode::from(
        u8::try_from(failed.min(100)).expect("clamped"),
    ))
}
